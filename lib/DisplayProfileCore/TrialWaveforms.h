// How a word update reaches the panel.
enum class WordPath : uint8_t {
  STOCK,     // the stock profile's refresh: the panel's reading waveform (task D1)
  TABLE,     // load `table` with setCustomLut, run one fast refresh, release it
  STOCK_UI,  // a fast refresh outside the reader scope: the SDK's own UI waveform (SE0400NQW47 Trial D)
};

struct WordWaveform {
  WordPath path = WordPath::STOCK;
  const uint8_t* table = nullptr;  // TABLE only
  // S2's waveform-only prediction (ms, frame transfer excluded), recomputed from the table by the
  // host tests; 0 where it cannot be computed (OTP and SE0400NQW47 tables, FR codes not documented).
  uint16_t predictedMs = 0;
  const char* name = "stock";  // the source table, for log lines and results files
};

// What a word update with `id` runs on `panel`. STOCK, and any profile on a panel it has no table
// for, gives the stock path: a profile the allow rule refuses never reaches a trial waveform even
// if a caller skipped the rule. SIMULATED gives STOCK too (the simulator models time, not glass).
WordWaveform wordWaveform(ProfileId id, PanelId panel);

