// The trial profiles' waveform tables and which one a word update runs on each panel
// (docs/spikes/S2-waveforms.md, sections 4, 6 and 7). Portable: plain flash constants, no SDK code.
//
// Origin and licence. Every byte comes from the FreeInk SDK pinned as the `freeink-sdk` submodule
// at commit 3f3e4c1126e2cb9a278c2c1076fb4a3334ffdc30, file
// freeink-sdk/libs/display/FreeInkDisplay/src/lut/Ssd1677Luts.h. The SDK is MIT licensed,
// "Copyright (c) 2026 FreeInk" (freeink-sdk/LICENSE, freeink-sdk/NOTICE); the SDK says its Picco
// tables were copied byte for byte from the BOOX stock firmware (Ssd1677Luts.h, comment above
// lut_picco_fast), so that is where the underlying bytes come from. No table or code from any
// other project was used. test/display_profile/TrialWaveformsTest.cpp re-reads the SDK header and
// checks every carried-over byte, so a changed SDK table fails the host tests.
//
// SSD1677 110-byte table (S2 section 4; SDK: PaperMonoDriver.cpp:108-115, Ssd1677Driver.cpp
// setCustomLut()): bytes 0..49 are 5 LUT entries x 10 groups (4 phases A..D at 2 bits, phase A in
// the top bits; 00 = 0 V, 01 = VSH1, 10 = VSL, 11 = VSH2); bytes 50..99 are 10 groups x {TP_A, TP_B,
// TP_C, TP_D, RP} (TP in frames, a group runs RP + 1 times); bytes 100..104 frame-rate codes, one
// nibble per group, even group in the high nibble (code 2 = 50 Hz = 20 ms); bytes 105..109 VGH,
// VSH1, VSH2, VSL, VCOM. In a black-and-white differential update L0 is black to black, L1 black to
// white, L2 white to black, L3 white to white.

