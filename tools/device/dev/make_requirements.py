#!/usr/bin/env python3
"""Regenerate tools/device/requirements.txt and requirements-build.txt.

Developer tool, not part of the kit's runtime; needs network access to pypi.org.

Pins every package session.ps1 installs into the private Python, with the
SHA-256 of each file pip may download. For packages with compiled parts the
Windows x64 wheel for CPython 3.13 is pinned, plus the manylinux x86_64
wheel for the same Python so the identical file can be exercised with
``pip install --require-hashes`` in a Linux cloud session. esptool is
published as a source archive only; pip builds it locally with the pinned
setuptools (requirements-build.txt) and ``--no-build-isolation``.

Usage: python3 tools/device/dev/make_requirements.py
"""

import json
import os
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.dirname(HERE)

# esptool 5.6.0's full dependency tree on Windows, resolved from each wheel's
# Requires-Dist including Windows-only markers (rich-click needs colorama there).
RUNTIME = [
    ("esptool", "5.6.0", "sdist"),
    ("pyserial", "3.5", "any"),
    ("cryptography", "50.0.2", "binary"),
    ("cffi", "2.1.1", "binary"),
    ("pycparser", "3.12", "any"),
    ("reedsolo", "1.7.0", "any"),
    ("PyYAML", "6.0.3", "binary"),
    ("intelhex", "2.3.0", "any"),
    ("rich-click", "1.9.9", "any"),
    ("click", "8.5.1", "any"),
    ("colorama", "0.4.6", "any"),
    ("esp-pylib", "1.2.1", "any"),
    ("rich", "15.0.0", "any"),
    ("markdown-it-py", "4.3.0", "any"),
    ("mdurl", "0.1.2", "any"),
    ("Pygments", "2.21.0", "any"),
    ("websockets", "17.4", "binary"),
]
BUILD = [("setuptools", "84.2.1", "any")]


def files(name, version):
    with urllib.request.urlopen("https://pypi.org/pypi/%s/%s/json" % (name, version)) as r:
        return json.load(r)["urls"]


def wanted(f, kind):
    fn = f["filename"]
    if kind == "sdist":
        return f["packagetype"] == "sdist"
    if kind == "any":
        return fn.endswith("-none-any.whl")
    win = fn.endswith("-win_amd64.whl") and ("-cp313-cp313-" in fn or "-abi3-" in fn)
    lin = fn.endswith("_x86_64.whl") and "manylinux" in fn and ("-cp313-cp313-" in fn or "-abi3-" in fn)
    return win or lin


def render(pkgs, header):
    lines = [header]
    for name, version, kind in pkgs:
        chosen = sorted((f for f in files(name, version) if wanted(f, kind)), key=lambda f: f["filename"])
        if not chosen:
            raise SystemExit("no %s file for %s %s" % (kind, name, version))
        lines.append("# %s" % ", ".join(f["filename"] for f in chosen))
        lines.append("%s==%s \\" % (name, version))
        for i, f in enumerate(chosen):
            lines.append("    --hash=sha256:%s%s" % (f["digests"]["sha256"], " \\" if i < len(chosen) - 1 else ""))
    return "\n".join(lines) + "\n"


def main():
    head = ("# Generated by tools/device/dev/make_requirements.py; do not edit by hand.\n"
            "# session.ps1 installs these into its private Python with\n"
            "#   pip install --require-hashes --no-deps\n")
    with open(os.path.join(OUT, "requirements-build.txt"), "w") as fp:
        fp.write(render(BUILD, head + "# Build step: setuptools, to build esptool's source archive offline."))
    with open(os.path.join(OUT, "requirements.txt"), "w") as fp:
        fp.write(render(RUNTIME, head + "# Runtime: esptool (built from its source archive) and its dependencies."))
    print("written")


if __name__ == "__main__":
    main()
